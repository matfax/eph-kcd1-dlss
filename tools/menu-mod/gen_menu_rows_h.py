#!/usr/bin/env python3
"""gen_menu_rows_h.py: emit tools/asi/menu_rows.h from tools/menu-mod/MM_AdvancedGraphics.xml (the modded file).

The plugin (0.8.0, pak-free menu rows) patches the game's own MM_AdvancedGraphics.xml in memory. This script keeps
the modded XML the single source of truth: the added nodes (Id 980..997) become C string literals, split so that the
two "Unsupported" choice nodes (987, 994) can be left out when an upscaler exists. The 14 cvar<->row edges are copied
as text; the AddChoices call chain is generated in C from MENU_CHAIN_IDS. Run: python3 -I gen_menu_rows_h.py
"""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "MM_AdvancedGraphics.xml")
ORIG = "/mnt/cache/kcd-ui-extract/GameData/Libs/UI/UIActions/MM_AdvancedGraphics.xml"
OUT = os.path.join(HERE, "..", "asi", "menu_rows.h")
mod = open(SRC, "rb").read().decode("ascii")
orig = open(ORIG, "rb").read().decode("ascii")
node_re = re.compile(r'    <Node Id="(\d+)"[^\r\n]*\r\n      <Inputs [^\r\n]*\r\n    </Node>\r\n')
edge_re = re.compile(r'    <Edge [^\r\n]*\r\n')
nodes = {m.group(1): m.group(0) for m in node_re.finditer(mod) if m.group(0) not in orig}
edges = [m.group(0) for m in edge_re.finditer(mod) if m.group(0) not in orig]
chain = [e for e in edges if 'portIn="Call" portOut="OnCall"' in e and re.search(r'nodeOut="(824|9[89]\d)"', e)]
io = [e for e in edges if e not in chain]
assert sorted(nodes) == [str(i) for i in range(980, 998)], sorted(nodes)
assert len(io) == 14 and len(chain) == 13, (len(io), len(chain))
# chain order 824 -> 980 -> ... -> 557
nxt = {re.search(r'nodeOut="(\d+)"', e).group(1): re.search(r'nodeIn="(\d+)"', e).group(1) for e in chain}
ids = ["824"]
while ids[-1] in nxt: ids.append(nxt[ids[-1]])
assert ids[-1] == "557" and len(ids) == 14, ids
def lit(name, text):
    out = ["static const char %s[] =" % name]
    for line in text.split("\r\n")[:-1]:
        out.append('    "%s\\r\\n"' % line.replace("\\", "\\\\").replace('"', '\\"'))
    out[-1] += ";"
    return "\n".join(out)
a = "".join(nodes[str(i)] for i in (980, 981, 982, 983, 984, 985, 986, 988, 989, 990))
b = "".join(nodes[str(i)] for i in (991, 992, 993, 995, 996, 997))
h = ["/* generated by tools/menu-mod/gen_menu_rows_h.py from tools/menu-mod/MM_AdvancedGraphics.xml: do not edit. */",
     "/* AddChoicesButton/AddChoiceOption call chain, 824 (previous row) .. 557 (next row); 987/994 = the Unsupported choices */",
     "static const int MENU_CHAIN_IDS[] = { %s };" % ", ".join(ids),
     "#define MENU_UNSUPP_MODE 987\n#define MENU_UNSUPP_PRESET 994",
     lit("MENU_NODES_A", a), lit("MENU_NODE_UNSUPP_MODE", nodes["987"]), lit("MENU_NODES_B", b),
     lit("MENU_NODE_UNSUPP_PRESET", nodes["994"]), lit("MENU_EDGES_IO", "".join(io))]
open(OUT, "w").write("\n".join(h) + "\n")
print("wrote", OUT, len(a), len(b), len("".join(io)))
